'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { parseProject, parseLock, dependencyRoots } = require('../src/dependencies');
const { SymbolIndex, findDefinitions, projectRoot } = require('../src/lookup');

const commit = '9fceb02a41c3d5e6f708192a3b4c5d6e7f809102';

const files = {
  'app/aion.project': `name = "app"
packages = "aion-dependencies"   # downloaded by aion install

[dependencies]
http = { git = "https://example.com/http", tag = "v1" }  # pinned
geometry = { path = "../geometry" }
missing = { git = "https://example.com/missing", tag = "v1" }
`,
  'app/aion.lock': `# Generated by aion; pins git dependencies to exact commits.\n"https://example.com/http#tag:v1" = "${commit}"\n`,
  'app/main.aion': `import http
import http.parser
import http.get
from geometry import area
import geometry.shapes
import missing
import util

println(http.get(), area(2.0), util.local())
`,
  'app/util.aion': 'fn local() = 1\n',
  'app/aion-dependencies/http-9fceb02a41c3/lib.aion': 'fn get() = 1\n',
  'app/aion-dependencies/http-9fceb02a41c3/parser.aion': 'fn parse() = 1\n',
  'geometry/aion.project': 'name = "geometry"\nlib = "src/lib.aion"\n',
  'geometry/src/lib.aion': 'fn area(r: Float) = r\n',
  'geometry/shapes.aion': 'type Circle(r: Float)\n',
};

const base = fs.mkdtempSync(path.join(os.tmpdir(), 'aion-deps-'));
test.after(() => fs.rmSync(base, { recursive: true, force: true }));
for (const [name, text] of Object.entries(files)) {
  const file = path.join(base, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

const exists = (file) => fs.existsSync(file) && fs.statSync(file).isFile();
const read = (file) => (exists(file) ? fs.readFileSync(file, 'utf8') : undefined);
const index = new SymbolIndex(read);
const app = path.join(base, 'app');

/** Where the name at `before§after` in `app/main.aion` leads, as `file:line:character` relative to the temp folder. */
function definitions(before, after = '') {
  const full = path.join(app, 'main.aion');
  const text = fs.readFileSync(full, 'utf8');
  const marked = text.indexOf(before + after);
  assert.ok(marked >= 0, `not in main.aion: ${before + after}`);
  const offset = marked + before.length;
  const line = text.slice(0, offset).split('\n').length - 1;
  const character = offset - (text.lastIndexOf('\n', offset - 1) + 1);
  return findDefinitions({ file: full, text, line, character, index, exists, root: projectRoot(full, exists) })
    .map((at) => `${path.relative(base, at.file).replace(/\\/g, '/')}:${at.line}:${at.character}`)
    .sort();
}

test('aion.project is read for its packages folder, library and dependencies', () => {
  const project = parseProject(files['app/aion.project']);
  assert.equal(project.packages, 'aion-dependencies');
  assert.deepEqual(project.dependencies[0], { name: 'http', git: 'https://example.com/http', tag: 'v1' });
  assert.deepEqual(project.dependencies[1], { name: 'geometry', path: '../geometry' });
  assert.equal(parseProject(files['geometry/aion.project']).lib, 'src/lib.aion');
  assert.deepEqual(parseProject('name = "x"\n[dependencies]\n').dependencies, []);
  assert.equal(parseProject('# packages = "no"\nname = "x"\n').packages, undefined);
});

test('aion.lock is read as pinned commits by the key aion writes', () => {
  assert.equal(parseLock(files['app/aion.lock']).get('https://example.com/http#tag:v1'), commit);
  assert.equal(parseLock('').size, 0);
});

test('path dependencies are found where they point, git dependencies in the packages folder at the pinned commit', () => {
  const found = dependencyRoots(app, read, exists);
  assert.equal(found.get('geometry').dir, path.join(base, 'geometry'));
  assert.equal(found.get('geometry').library, path.join(base, 'geometry/src/lib.aion'));
  assert.equal(found.get('http').dir, path.join(app, 'aion-dependencies/http-9fceb02a41c3'));
  assert.equal(found.get('http').library, path.join(app, 'aion-dependencies/http-9fceb02a41c3/lib.aion'));
  assert.equal(found.get('missing'), undefined, 'a git dependency with no pin has nowhere to be');
  assert.equal(dependencyRoots(path.join(base, 'nowhere'), read, exists).size, 0);
});

test('a git dependency is not found without a packages folder (it lives in the cache)', () => {
  const text = files['app/aion.project'].replace('packages = "aion-dependencies"', '');
  const found = dependencyRoots(app, (file) => (file.endsWith('aion.project') ? text : read(file)), exists);
  assert.equal(found.get('http'), undefined);
  assert.ok(found.get('geometry'));
});

test('import of a dependency leads to its library, and to a file inside it', () => {
  assert.deepEqual(definitions('import ht', 'tp\n'), ['app/aion-dependencies/http-9fceb02a41c3/lib.aion:0:0']);
  assert.deepEqual(definitions('import http.par', 'ser'), ['app/aion-dependencies/http-9fceb02a41c3/parser.aion:0:0']);
  assert.deepEqual(definitions('import geometry.sha', 'pes'), ['geometry/shapes.aion:0:0']);
  assert.deepEqual(definitions('import geo', 'metry.shapes'), ['geometry/src/lib.aion:0:0']);
});

test('a name taken from a dependency is found in its library', () => {
  assert.deepEqual(definitions('import http.g', 'et'), ['app/aion-dependencies/http-9fceb02a41c3/lib.aion:0:3']);
  assert.deepEqual(definitions('from geometry import ar', 'ea'), ['geometry/src/lib.aion:0:3']);
  assert.deepEqual(definitions('println(http.g', 'et()'), ['app/aion-dependencies/http-9fceb02a41c3/lib.aion:0:3']);
});

test('a module of the project wins over a dependency of the same name, and an unknown dependency leads nowhere', () => {
  assert.deepEqual(definitions('println(http.get(), area(2.0), util.lo', 'cal())'), ['app/util.aion:0:3']);
  assert.deepEqual(definitions('import miss', 'ing\n'), []);
});
